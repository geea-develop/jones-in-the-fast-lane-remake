#!/usr/bin/env node
/**
 * Post-build: generate a service-worker precache manifest from the static
 * export in `out/`. This lets the SW cache the full app shell (HTML + all
 * hashed JS/CSS/font chunks) at install time, so a hard reload works fully
 * offline instead of relying on lazily-cached-on-first-request assets.
 *
 * Emits `out/sw-precache-manifest.js` which sw.js loads via importScripts().
 */
const fs = require("fs");
const path = require("path");

const OUT = path.join(__dirname, "..", "out");
const BASE = process.env.NEXT_PUBLIC_BASE_PATH || "";

if (!fs.existsSync(OUT)) {
  console.error("[precache] out/ not found — did `next build` (export) run?");
  process.exit(0); // don't fail the build in non-export contexts
}

// Cache the app shell entry points and all immutable static assets.
// (Skip source maps and the manifest itself.)
const INCLUDE_EXT = new Set([".html", ".js", ".css", ".woff2", ".woff", ".png", ".svg", ".webmanifest", ".json"]);
const SKIP = new Set(["sw.js", "sw-precache-manifest.js"]);

/** @type {string[]} */
const urls = [];

function walk(dir) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      walk(full);
      continue;
    }
    if (SKIP.has(entry.name)) continue;
    if (entry.name.endsWith(".map")) continue;
    if (!INCLUDE_EXT.has(path.extname(entry.name))) continue;
    const rel = path.relative(OUT, full).split(path.sep).join("/");
    urls.push(`${BASE}/${rel}`);
  }
}

walk(OUT);

// Ensure the root navigation entry is present.
const shell = new Set(urls);
shell.add(`${BASE}/`);
shell.add(`${BASE}/index.html`);

const list = Array.from(shell).sort();
const body = `// AUTO-GENERATED by scripts/generate-precache-manifest.cjs — do not edit.\nself.__PRECACHE_MANIFEST = ${JSON.stringify(list, null, 2)};\n`;

fs.writeFileSync(path.join(OUT, "sw-precache-manifest.js"), body);
console.log(`[precache] wrote ${list.length} entries to out/sw-precache-manifest.js`);
